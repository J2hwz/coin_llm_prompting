"""
bnirl.py
--------
Bayesian Non-parametric IRL (BNIRL) — Fixed-K=2 Gibbs sampler for subgoal
inference.

Algorithm
---------
Assumes each trajectory step is generated by either a latent subgoal or the
terminal goal (K=2 mixture). Alternates between:
  1. Sampling step assignments to subgoal vs. terminal goal.
  2. Sampling the subgoal location given the assigned steps.

After burn-in, the subgoal samples form a 2-D histogram over grid cells.
The mode of the post-burn-in samples is the predicted subgoal.

Reference
---------
Adapted from jupyter_demos/BNIRL/append_sections.py.
Key change: global GRID constant replaced with explicit (grid_rows, grid_cols).

Public API
----------
    run_bnirl(paths, layout, n_iter=500, burn_in=100, alpha=3.0, seed=42)
        -> (score_grid_display, predicted_json_coords)

Coordinate conventions
----------------------
- JSON coords : (col, row_from_top)  — row 0 = top of grid image
- MDP coords  : (x, y_mdp)           — y=0 = bottom row
- Internally, all positions are in MDP coords; score grid is flipped for display.
"""

